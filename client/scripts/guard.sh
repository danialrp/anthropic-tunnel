#!/bin/bash
# Leak guard (macOS, pf). Blocks every outgoing packet to Anthropic addresses
# unless it leaves through this project's utun. Independent of sing-box: when
# the daemon is down, or another VPN owns the routes, nothing reaches
# Anthropic directly. Rules live in our own anchor under Apple's
# "com.apple/*" hook, so /etc/pf.conf is never edited.
#   guard.sh apply    (launchd, every 5 s) enable pf, (re)load the anchor with
#                     the current utun name, write the status file
#   guard.sh refresh  (launchd, every 5 min) update the dynamic address table
#                     through the tunnel
#   guard.sh selftest check that Anthropic works through the tunnel and that a
#                     guarded address is refused on the physical interface
#   guard.sh down     remove the anchor and release our pf reference
#   guard.sh status   print anchor rules, tables and pf state
set -u
. "$(dirname "$0")/common.sh"
need_root
PFCTL=/sbin/pfctl
RULES="$VAR/guard-anchor.conf"
APPLIED="$VAR/guard-anchor.applied"
DYN="$VAR/guard-dynamic.txt"
NEW="$VAR/guard-dynamic.new"
TOKENS="$VAR/guard-pf.tokens"
STATUS="$ETC/guard-status"
LOG="$LOGDIR/guard.log"
install -d -m 700 "$VAR"; install -d -m 755 "$LOGDIR"; touch "$DYN"

log() { printf '%s %s\n' "$(date '+%Y-%m-%d %H:%M:%S')" "$*" >> "$LOG"; }

our_utun() {
  ifconfig 2>/dev/null | awk -v a="$TUN_ADDR" '/^[a-z0-9]+: /{i=$1; sub(":","",i)} $1=="inet" && $2==a {print i; exit}'
}

render_rules() {
  u=$(our_utun)
  {
    echo "# generated by guard.sh; do not edit"
    echo "table <anthropic_static> persist { $GUARD_STATIC }"
    echo "table <anthropic_dynamic> persist file \"$DYN\""
    if [ -n "$u" ]; then
      echo "pass out quick on $u to <anthropic_static>"
      echo "pass out quick on $u to <anthropic_dynamic>"
    fi
    echo "block return out quick to <anthropic_static>"
    echo "block return out quick to <anthropic_dynamic>"
  } > "$RULES.new"
  mv "$RULES.new" "$RULES"
  printf '%s' "$u"
}

pf_enabled() { $PFCTL -s info 2>/dev/null | grep -q 'Status: Enabled'; }

write_status() {
  n=$(grep -c . "$DYN" 2>/dev/null || true)
  printf '%s %s %s %s\n' "$1" "${n:-0}" "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "${2:--}" > "$STATUS.new"
  chmod 644 "$STATUS.new"; mv "$STATUS.new" "$STATUS"
}

apply() {
  if ! pf_enabled; then
    tok=$($PFCTL -E 2>&1 | awk '/Token/{print $NF}')
    [ -n "$tok" ] && echo "$tok" >> "$TOKENS"
    log "pf was disabled: enabled it (token ${tok:-none})"
  fi
  # Apple's main ruleset must still carry the com.apple/* hook, or our anchor is never evaluated
  if ! $PFCTL -s rules 2>/dev/null | grep -q 'anchor "com.apple/\*"'; then
    $PFCTL -q -f /etc/pf.conf 2>>"$LOG" && log "main ruleset lacked the com.apple hook: reloaded /etc/pf.conf"
    : > "$APPLIED"
  fi
  u=$(render_rules)
  loaded=$($PFCTL -a "$GUARD_ANCHOR" -s rules 2>/dev/null | grep -c . || true)
  if ! cmp -s "$RULES" "$APPLIED" || [ "${loaded:-0}" -eq 0 ]; then
    if $PFCTL -q -a "$GUARD_ANCHOR" -f "$RULES" 2>>"$LOG"; then
      cp "$RULES" "$APPLIED"; log "anchor loaded (tunnel interface: ${u:-none, everything to Anthropic blocked})"
    else
      log "anchor load FAILED"; write_status error "$u"; return 1
    fi
  fi
  write_status on "$u"
}

refresh() {
  if bash "$BIN/guard-ips.sh" "$ETC/clash-api.secret" > "$NEW" 2>>"$LOG" && [ -s "$NEW" ]; then
    if ! cmp -s "$NEW" "$DYN"; then
      install -m 600 "$NEW" "$DYN"
      $PFCTL -q -a "$GUARD_ANCHOR" -t anthropic_dynamic -T replace -f "$DYN" 2>>"$LOG" && log "dynamic table: $(grep -c . "$DYN") addresses"
    fi
  else
    log "refresh skipped: local API unavailable, kept the last list"
  fi
}

# exit 0 = both fine, 2 = Anthropic not reachable through the tunnel, 3 = guard not refusing
selftest() {
  code=$(curl -s --max-time 15 -o /dev/null -w '%{http_code}' https://api.anthropic.com/v1/models || true)
  echo "Anthropic through the tunnel: HTTP $code (expect 401)"; [ "$code" = 401 ] || return 2
  ok=yes
  phys=$(netstat -rn -f inet | awk '$1=="default" && $NF !~ /^utun/ {print $NF; exit}')
  # a fake-IP address is guarded like Anthropic's ranges but routes nowhere: safe to probe on the physical link
  out=$(curl -s --interface "$phys" --max-time 5 -o /dev/null -w '%{http_code} %{time_total}' http://198.18.255.254/ 2>/dev/null || true)
  code2=${out%% *}; secs=${out##* }
  echo "guarded address via $phys: HTTP $code2 after ${secs}s (expect 000 in well under 1 s: refused by the guard, not a timeout)"
  awk -v c="$code2" -v s="$secs" 'BEGIN { exit !(c == "000" && s + 0 < 1) }' || ok=no
  [ "$ok" = yes ] || return 3
}

case "${1:-}" in
  apply) apply ;;
  refresh) refresh ;;
  selftest) selftest ;;
  down)
    $PFCTL -q -a "$GUARD_ANCHOR" -F all 2>/dev/null || true
    if [ -s "$TOKENS" ]; then while read -r t; do $PFCTL -q -X "$t" 2>/dev/null || true; done < "$TOKENS"; : > "$TOKENS"; fi
    : > "$APPLIED"
    write_status off
    log "guard down"
    echo "leak guard DOWN"
    ;;
  status)
    $PFCTL -s info 2>/dev/null | grep Status
    $PFCTL -a "$GUARD_ANCHOR" -s rules 2>/dev/null
    for t in anthropic_static anthropic_dynamic; do echo "<$t>:"; $PFCTL -a "$GUARD_ANCHOR" -t "$t" -T show 2>/dev/null; done
    cat "$STATUS" 2>/dev/null
    ;;
  *) echo "usage: $0 apply|refresh|selftest|down|status" >&2; exit 2 ;;
esac
