# ---------- helpers ----------
def read(path):
    try:
        with open(path) as f: return f.read().strip()
    except OSError: return ""

def secret():
    return read(SECRET_FILE)

def api(path, method="GET", body=None, timeout=4):
    req = urllib.request.Request(API + path, method=method,
                                 headers={"Authorization": "Bearer " + secret(),
                                          "Content-Type": "application/json"},
                                 data=json.dumps(body).encode() if body is not None else None)
    with urllib.request.urlopen(req, timeout=timeout) as r:
        raw = r.read()
        return json.loads(raw) if raw else {}

def sh(cmd, timeout=8):
    try:
        return subprocess.run(cmd, capture_output=True, text=True, timeout=timeout).stdout
    except Exception:
        return ""

def daemon_loaded():
    if LINUX:
        return subprocess.run(["systemctl", "is-enabled", "--quiet", UNIT], capture_output=True).returncode == 0
    return subprocess.run(["launchctl", "print", "system/" + LABEL],
                          capture_output=True).returncode == 0

def process_running():
    if LINUX:
        return subprocess.run(["systemctl", "is-active", "--quiet", UNIT], capture_output=True).returncode == 0
    return subprocess.run(["pgrep", "-x", "sing-box"], capture_output=True).returncode == 0

def tun_up():
    if LINUX:
        return "inet 172.30.250.1" in sh(["ip", "-4", "addr", "show", TUN_IF])
    return "172.19.0.1" in sh(["ifconfig"])

def resolver_state():
    """macOS: which /etc/resolver files exist. Linux: the resolved routing domains on the dummy link."""
    if LINUX:
        out = sh(["resolvectl", "status", DNS_LINK])
        return " ".join(w for w in out.split() if w.startswith("~")) or "dns layer down"
    return ", ".join(d for d in
        ["anthropic.com","claude.ai","claude.com","claude.app","claudeusercontent.com","claudemcpcontent.com"]
        if os.path.exists("/etc/resolver/" + d))

def lookup_claude():
    if LINUX:
        return sh(["resolvectl", "query", "claude.ai"]).strip().split("\n")[0]
    return sh(["dscacheutil", "-q", "host", "-a", "name", "claude.ai"]).strip().replace("\n", " ")

def server_ip():
    return read(SERVER_IP_FILE)

def server_tcp_reachable():
    ip = server_ip()
    if not ip: return None
    try:
        with socket.create_connection((ip, 22), timeout=3): return True
    except OSError: return False

def guard_info():
    """Leak guard state from its status file: (ok, text)."""
    parts = read(GUARD_STATUS).split()
    if not parts:
        return False, "not installed"
    state, count, stamp = (parts + ["", "0", ""])[:3]
    try:
        age = time.time() - calendar.timegm(time.strptime(stamp, "%Y-%m-%dT%H:%M:%SZ"))
    except ValueError:
        age = 1e9
    if state != "on":
        return False, state
    if age > GUARD_STALE:
        return False, f"not refreshed for {int(age)} s"
    return True, f"on, {count} extra addresses"

def bypass_risks():
    """Things that route traffic around any packet filter: system proxies and transparent proxies."""
    risks = []
    out = sh(["scutil", "--proxy"], 3)
    for key, name in (("HTTPEnable", "HTTP"), ("HTTPSEnable", "HTTPS"), ("SOCKSEnable", "SOCKS"),
                      ("ProxyAutoConfigEnable", "PAC")):
        if f"{key} : 1" in out:
            risks.append(f"system proxy ({name})")
    for line in sh(["systemextensionsctl", "list"], 5).splitlines():
        if "[activated enabled]" in line and any(k in line for k in ("ransparentProxy", "AppProxy", "ilterData")):
            risks.append("network extension proxy: " + line.split("\t")[-2].strip() if "\t" in line else "network extension proxy")
    return risks

def other_vpns():
    """Connected VPN services other than this tunnel (informational: the guard blocks them from Anthropic)."""
    names = []
    for line in sh(["scutil", "--nc", "list"], 3).splitlines():
        if "(Connected)" in line and '"' in line:
            names.append(line.split('"')[1])
    return names

def load_state():
    try:
        with open(STATE_FILE) as f: return json.load(f)
    except Exception: return {}

def save_state(st):
    os.makedirs(STATE_DIR, exist_ok=True)
    with open(STATE_FILE, "w") as f: json.dump(st, f)

def human(n):
    for unit in ("B", "KB", "MB", "GB"):
        if n < 1024: return f"{n:.0f} {unit}"
        n /= 1024
    return f"{n:.1f} TB"

def rate(bps):
    return human(bps) + "/s"

def short_rate(bps):
    for unit in ("B", "K", "M", "G"):
        if bps < 1024: return f"{bps:.0f}{unit}"
        bps /= 1024
    return f"{bps:.0f}T"

def notify(title, body):
    try:
        if LINUX:
            subprocess.run(["notify-send", title, body], capture_output=True)
        else:
            subprocess.run(["osascript", "-e",
                            f'display notification "{body}" with title "{title}"'], capture_output=True)
    except Exception:
        pass   # no notifier installed: never break the plugin over a notification

def fmt_uptime(sec):
    sec = int(sec); h, m = sec // 3600, (sec % 3600) // 60
    return f"{h}h {m:02d}m" if h else f"{m}m"

# ---------- actions ----------
def do_action(name, arg=None):
    if name == "connect":   sh(["sudo", "-n", BIN + "/tunnel-up.sh"], 30)
    elif name == "disconnect": sh(["sudo", "-n", BIN + "/tunnel-down.sh"], 30)
    elif name == "restart": sh(["sudo", "-n", BIN + "/tunnel-restart.sh"], 30)
    elif name == "transport" and arg:
        try: api("/proxies/anthropic", "PUT", {"name": arg})
        except Exception: pass
    elif name == "log":
        if LINUX:
            term = shutil.which("gnome-terminal") or shutil.which("x-terminal-emulator")
            if term:
                subprocess.Popen([term, "--", "journalctl", "-fu", UNIT] if term.endswith("gnome-terminal")
                                 else [term, "-e", f"journalctl -fu {UNIT}"])
        else:
            subprocess.run(["open", "-a", "Console", LOG])
    elif name == "diag":
        txt = diagnostics()
        if LINUX:
            clip = shutil.which("wl-copy") or shutil.which("xclip")
            if clip:
                p = subprocess.Popen([clip] + (["-selection", "clipboard"] if clip.endswith("xclip") else []),
                                     stdin=subprocess.PIPE); p.communicate(txt.encode())
            else:
                path = os.path.expanduser("~/anthropic-tunnel-diagnostics.txt")
                with open(path, "w") as f: f.write(txt)
                notify("Anthropic tunnel", f"Diagnostics written to {path} (no wl-copy/xclip)")
        else:
            p = subprocess.Popen(["pbcopy"], stdin=subprocess.PIPE); p.communicate(txt.encode())
    elif name == "flushdns":
        sh(["resolvectl", "flush-caches"] if LINUX else ["dscacheutil", "-flushcache"])
    if not LINUX:
        subprocess.run(["open", "-g", "swiftbar://refreshplugin?name=anthropic-tunnel"], capture_output=True)

def diagnostics():
    out = [f"anthropic-tunnel diagnostics {time.strftime('%Y-%m-%d %H:%M:%S')}"]
    out.append(f"daemon loaded: {daemon_loaded()}  process: {process_running()}")
    out.append(("dns layer: " if LINUX else "resolver files: ") + resolver_state())
    out.append("tun: " + ("up" if tun_up() else "down"))
    out.append("claude.ai -> " + lookup_claude())
    try: out.append("selector: " + json.dumps(api("/proxies/anthropic")))
    except Exception as e: out.append(f"api error: {e}")
    out.append("server tcp/22: " + str(server_tcp_reachable()))
    out.append("log tail:\n" + (sh(["journalctl", "-u", UNIT, "-n", "15", "--no-pager", "-o", "cat"]) if LINUX
                                else sh(["tail", "-n", "15", LOG])))
    return "\n".join(out)

# ---------- status ----------
def gather():
    st = load_state()
    now = time.time()
    info = {"loaded": daemon_loaded(), "running": process_running(), "api": False,
            "selector": None, "all": [], "delay": None, "delay_err": "",
            "conns": [], "anth_up": 0, "anth_down": 0, "rate_up": 0.0, "rate_down": 0.0,
            "recent": False, "server_tcp": None, "started": st.get("started")}
    if info["loaded"] and info["running"]:
        try:
            sel = api("/proxies/anthropic")
            info["api"] = True
            info["selector"] = sel.get("now"); info["all"] = sel.get("all", [])
        except Exception:
            info["api"] = False
    if info["api"]:
        try:
            d = api(f"/proxies/{info['selector']}/delay?url={urllib.parse.quote(DELAY_URL, safe='')}&timeout=4000", timeout=6)
            info["delay"] = d.get("delay")
        except urllib.error.HTTPError as e:
            info["delay_err"] = f"HTTP {e.code}"
        except Exception as e:
            info["delay_err"] = str(e)[:40]
        try:
            conns = api("/connections").get("connections", [])
        except Exception:
            conns = []
        prev = st.get("bytes", {})
        first_run = "t" not in st
        cur = {}
        delta = 0
        for c in conns:
            if "anthropic" not in c.get("chains", []): continue
            m = c.get("metadata", {})
            host = m.get("host") or m.get("sniffHost") or m.get("destinationIP", "")
            up, down = c.get("upload", 0), c.get("download", 0)
            info["conns"].append((host, up, down))
            info["anth_up"] += up; info["anth_down"] += down
            cur[c["id"]] = [up, down]
            pu, pd = prev.get(c["id"], [up, down] if first_run else [0, 0])
            delta_up, delta_down = max(0, up - pu), max(0, down - pd)
            delta += delta_up + delta_down
            info["rate_up"] += delta_up; info["rate_down"] += delta_down
        interval = max(1.0, now - st.get("t", now - 5))
        info["rate_up"] /= interval; info["rate_down"] /= interval
        if delta >= ACTIVE_MIN_BYTES: st["last_active"] = now
        st["bytes"] = cur
        info["recent"] = (now - st.get("last_active", 0)) < ACTIVE_WINDOW
        # session totals survive connection closes: accumulate deltas
        if not first_run:
            st["sess_up"] = st.get("sess_up", 0) + sum(max(0, cur[i][0] - prev.get(i, [0, 0])[0]) for i in cur)
            st["sess_down"] = st.get("sess_down", 0) + sum(max(0, cur[i][1] - prev.get(i, [0, 0])[1]) for i in cur)
        info["sess_up"], info["sess_down"] = st.get("sess_up", 0), st.get("sess_down", 0)
    else:
        st["bytes"] = {}
        info["sess_up"], info["sess_down"] = st.get("sess_up", 0), st.get("sess_down", 0)

    # state machine
    if not info["loaded"]:
        state = "grey"; label = "OFF"
    elif not info["running"] or not info["api"]:
        state = "grey"; label = "?"
    elif info["delay"] is None and st.get("fail_count", 0) + 1 < RED_AFTER_FAILURES:
        # one failed probe: keep the last good state, mark it, try again next tick
        st["fail_count"] = st.get("fail_count", 0) + 1
        state = st.get("state") if st.get("state") in ("green", "yellow") else "green"
        label = "·"
        info["delay"] = st.get("last_delay")
    elif info["delay"] is None:
        st["fail_count"] = st.get("fail_count", 0) + 1
        state = "red"; label = "DOWN"
        info["server_tcp"] = server_tcp_reachable()
    elif info["recent"]:
        st["fail_count"] = 0; st["last_delay"] = info["delay"]
        state = "yellow"
        label = (f"↓{short_rate(info['rate_down'])}" if info['rate_down'] > 0
                 else f"↑{short_rate(info['rate_up'])}" if info['rate_up'] > 0 else "↓0")
    else:
        st["fail_count"] = 0; st["last_delay"] = info["delay"]
        state = "green"; label = "✓"   # never empty: SwiftBar hides an item with an empty title

    # leak protection (macOS): a missing guard or an active proxy outranks every other state
    if LINUX:
        info["guard_ok"], info["guard"], info["bypass"], info["other_vpn"] = True, "", [], []
    else:
        info["guard_ok"], info["guard"] = guard_info()
        info["bypass"] = bypass_risks() if info["loaded"] else []
        info["other_vpn"] = other_vpns() if info["loaded"] else []
    warn = ""
    if info["loaded"] and not info["guard_ok"]:
        state, label, warn = "red", "GUARD", f"Leak guard {info['guard']}: Anthropic traffic could leave outside the tunnel"
    elif info["bypass"]:
        state, label, warn = "red", "PROXY", "Bypass risk: " + ", ".join(info["bypass"]) + ". Apps using it send Anthropic traffic around the tunnel"
    info["warning"] = warn
    if warn and warn != st.get("warning"):
        notify("Anthropic tunnel: leak risk", warn)
    st["warning"] = warn

    # uptime bookkeeping and notifications
    if state in ("green", "yellow") and not st.get("started"): st["started"] = now
    if state in ("grey", "red"): st["started"] = None
    if state in ("grey",) and info["loaded"] is False: st["sess_up"] = st["sess_down"] = 0
    prev_state = st.get("state")
    if prev_state and prev_state != state:
        if state == "red": notify("Anthropic tunnel DOWN", "Anthropic traffic is blocked (kill switch)")
        elif prev_state == "red": notify("Anthropic tunnel UP", "Traffic flows through the tunnel again")
        elif state == "grey" and not info["loaded"]: notify("Anthropic tunnel OFF", "Disabled by user. Anthropic traffic goes direct")
        elif prev_state == "grey" and state in ("green", "yellow"): notify("Anthropic tunnel ON", "Connected via " + str(info["selector"]))
    st["state"] = state; st["t"] = now
    info["started"] = st.get("started")
    save_state(st)
    return state, label, info

def item(text, **kw):
    if LINUX:
        # Argos (BitBar format): no light,dark colour pairs, no sfimage/sfcolor/disabled/checked
        if "color" in kw and "," in kw["color"]: kw["color"] = kw["color"].split(",")[1]   # dark top bar
        for k in ("sfimage", "sfcolor", "disabled", "font"): kw.pop(k, None)   # GNOME uses its own font
        if kw.pop("checked", "false") == "true": text = "\u2713 " + text
    params = " ".join(f"{k}={v}" for k, v in kw.items())
    return f"{text} | {params}" if params else text

def action_item(text, action, arg=None, enabled=True, prefix=""):
    kw = {"bash": SELF, "param1": "--action", "param2": action, "terminal": "false", "refresh": "true"}
    if arg: kw["param3"] = arg
    if not enabled: kw = {"disabled": "true"}
    return prefix + item(text, **kw)

def render():
    state, label, info = gather()
    color = COLORS[state]
    print(item(label, image=ICONS[state], color=color, size=12, font="HelveticaNeue-Bold", length=14))
    print("---")
    # status line
    if state == "grey" and not info["loaded"]:
        status = "Disabled by user: Anthropic traffic goes DIRECT"
    elif state == "grey":
        status = "Daemon starting or API unreachable"
    elif info.get("warning"):
        status = info["warning"]
    elif state == "red":
        status = f"Tunnel DOWN via {info['selector']}: Anthropic traffic BLOCKED ({info['delay_err'] or 'no reply'})"
    else:
        up = fmt_uptime(time.time() - info["started"]) if info.get("started") else "-"
        status = f"Connected via {info['selector']} · {info['delay']} ms · up {up}"
    print(item(status, sfimage="circle.fill", sfcolor=color))
    if info["loaded"] and not LINUX:
        print(item("Leak guard: " + info["guard"], disabled="true"))
    for v in info.get("other_vpn", []):
        print(item(f"Other VPN connected: {v} (Anthropic stays blocked outside the tunnel)", disabled="true"))
    print("---")
    loaded = info["loaded"]
    print(action_item("Connect", "connect", enabled=not loaded))
    print(action_item("Disconnect", "disconnect", enabled=loaded))
    print(action_item("Restart tunnel", "restart", enabled=loaded))
    print("---")
    # transport submenu
    print(item("Transport", disabled="true") if not info["all"] else "Transport")
    for t in info["all"]:
        selected = t == info["selector"]
        if LINUX:   # Argos has no checked=; mark the active transport in the label
            print(action_item(("\u2713 " if selected else "\u2003 ") + t, "transport", arg=t, prefix="--"))
        else:
            print(action_item(t, "transport", arg=t, prefix="--") + f" checked={'true' if selected else 'false'}")
    # stats submenu
    print("Stats")
    print(item(f"--Session upload: {human(info.get('sess_up', 0))}", disabled="true"))
    print(item(f"--Session download: {human(info.get('sess_down', 0))}", disabled="true"))
    print(item(f"--Current rate: ↑{rate(info['rate_up'])} ↓{rate(info['rate_down'])}", disabled="true"))
    print(item(f"--Active Anthropic connections: {len(info['conns'])}", disabled="true"))
    hosts = {}
    for h, u, d in info["conns"]:
        hosts[h] = hosts.get(h, 0) + u + d
    for h, b in sorted(hosts.items(), key=lambda x: -x[1])[:12]:
        print(item(f"--  {h}  {human(b)}", disabled="true", font="Menlo", size=11))
    print("---")
    if state == "red":
        srv = info["server_tcp"]
        print(item("Server reachable (tcp/22): " + ("yes" if srv else "no" if srv is False else "n/a"), disabled="true"))
        print(item("Anthropic via tunnel: no", disabled="true"))
    else:
        print(item("Anthropic via tunnel: " + ("yes" if info["delay"] is not None else "n/a"), disabled="true"))
    print("---")
    print(action_item("Open log", "log"))
    print(action_item("Copy diagnostics", "diag"))
    print(action_item("Flush DNS cache", "flushdns"))

if __name__ == "__main__":
    if len(sys.argv) >= 3 and sys.argv[1] == "--action":
        do_action(sys.argv[2], sys.argv[3] if len(sys.argv) > 3 else None)
    else:
        try:
            render()
        except Exception as e:
            print(item("ERR", image=ICONS["grey"], color=COLORS["grey"]))
            print("---"); print(f"plugin error: {e}")
